#!/usr/bin/env python3
# 10/27/2026: Makes the GUI icons from gui/icons/svg/icons.txt.
#
#   gui/icons/svg/NAME.svg        one SVG per toolbar/menu/dialog icon
#   gui/icons/svg/app.svg         the application icon
#   gui/epdb_icons.h              the SVGs as C strings, built into the program
#   gui/icons/encrypted_password_database.ico   Windows icon, 16 to 256 px
#   gui/linux/icons/NxN.png       Linux icons, 16 to 256 px, and scalable SVG
#
# Run from any directory: python3 gui/tools/make_icons.py
# Needs rsvg-convert (librsvg2-tools) and Python 3 with PIL.

import io
import os
import struct
import subprocess
import sys

from PIL import Image

GUI = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SVG_DIR = os.path.join(GUI, 'icons', 'svg')
INK = '#1B1F24'
ACCENT = '#1F5FBF'
ACCENT_ICONS = ('new_db', 'add_record', 'smart_card', 'security')

APP_SVG = '''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
<rect width="64" height="64" rx="14" fill="#1F5FBF"/>
<ellipse cx="29" cy="20" rx="14" ry="5" fill="none" stroke="#fff" stroke-width="4"/>
<path d="M15 20v22c0 2.8 6.3 5 14 5M43 20v8M15 31c0 2.8 6.3 5 14 5" fill="none" stroke="#fff" stroke-width="4"/>
<circle cx="46" cy="45" r="13" fill="#fff"/>
<rect x="40" y="44" width="12" height="9" rx="2" fill="#1F5FBF"/>
<path d="M42.5 44v-3a3.5 3.5 0 0 1 7 0v3" fill="none" stroke="#1F5FBF" stroke-width="2.5"/>
</svg>
'''


def icon_svg(name, d):
    stroke = ACCENT if name in ACCENT_ICONS else INK
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
            'stroke="%s" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">'
            '<path d="%s"/></svg>\n' % (stroke, d))


def raster(svg_text, size):
    png = subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size), '-f', 'png'],
                         input=svg_text.encode(), stdout=subprocess.PIPE, check=True).stdout
    return Image.open(io.BytesIO(png)).convert('RGBA')


def ico_entry_dib(img):
    # 32 bpp BGRA DIB with an all-zero AND mask, bottom-up rows
    w, h = img.size
    px = img.tobytes('raw', 'BGRA')
    rows = [px[y * w * 4:(y + 1) * w * 4] for y in range(h)]
    xor = b''.join(reversed(rows))
    mask_row = ((w + 31) // 32) * 4
    andmask = b'\0' * (mask_row * h)
    hdr = struct.pack('<IiiHHIIiiII', 40, w, h * 2, 1, 32, 0, len(xor) + len(andmask), 0, 0, 0, 0)
    return hdr + xor + andmask


def write_ico(path, images):
    entries = []
    for img in images:
        w = img.size[0]
        if w >= 256:
            buf = io.BytesIO()
            img.save(buf, 'PNG')
            data = buf.getvalue()
        else:
            data = ico_entry_dib(img)
        entries.append((w, data))
    out = struct.pack('<HHH', 0, 1, len(entries))
    offset = 6 + 16 * len(entries)
    for w, data in entries:
        out += struct.pack('<BBBBHHII', w % 256, w % 256, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    for w, data in entries:
        out += data
    with open(path, 'wb') as f:
        f.write(out)


def c_string(text):
    s = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '')
    return '"%s"' % s


def main():
    icons = []
    with open(os.path.join(SVG_DIR, 'icons.txt')) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            name, d = line.split(' ', 1)
            icons.append((name, icon_svg(name, d)))
    for name, svg in icons:
        with open(os.path.join(SVG_DIR, name + '.svg'), 'w') as f:
            f.write(svg)
    with open(os.path.join(SVG_DIR, 'app.svg'), 'w') as f:
        f.write(APP_SVG)

    with open(os.path.join(GUI, 'epdb_icons.h'), 'w') as f:
        f.write('// Generated by gui/tools/make_icons.py from gui/icons/svg, do not edit.\n')
        f.write('#ifndef __EPDB_ICONS_H__\n#define __EPDB_ICONS_H__\n\n')
        f.write('struct EPDBIconSVG { const char *name; const char *svg; };\n\n')
        f.write('static const EPDBIconSVG epdb_icon_svgs[] = {\n')
        for name, svg in icons + [('app', APP_SVG)]:
            f.write('  { "%s", %s },\n' % (name, c_string(svg)))
        f.write('  { 0, 0 }\n};\n\n#endif // __EPDB_ICONS_H__\n')

    sizes = [16, 20, 24, 32, 40, 48, 64, 256]
    write_ico(os.path.join(GUI, 'icons', 'encrypted_password_database.ico'), [raster(APP_SVG, s) for s in sizes])
    linux_dir = os.path.join(GUI, 'linux', 'icons')
    os.makedirs(linux_dir, exist_ok=True)
    for s in [16, 22, 24, 32, 48, 64, 128, 256]:
        raster(APP_SVG, s).save(os.path.join(linux_dir, '%dx%d.png' % (s, s)))
    with open(os.path.join(linux_dir, 'scalable.svg'), 'w') as f:
        f.write(APP_SVG)
    raster(APP_SVG, 48).save(os.path.join(GUI, 'linux', 'encrypted_password_database.png'))
    print('%d icons, app icon, epdb_icons.h, .ico and Linux PNGs written' % len(icons))


if __name__ == '__main__':
    sys.exit(main())
